export type MediaFieldKey='TITLE'|'APPLY_DEADLINE'|'EVENT_DATE'|'APPLY_MODE'|'ENROLLMENT'|'CAMPUS'|'COHORT_MIN'|'PRIORITY'|'COMPLETION';
export interface MediaTextSpan {kind:'TEXT';sourceRevisionId:string;paragraphId:string;start:number;end:number;quote:string}
export interface MediaImageSpan {kind:'IMAGE';sourceRevisionId:string;originalSha256:string;pageIndex:0;
  bboxNorm:PixelBox;quote:string;coordinateSystem:'ORIGINAL_TOP_LEFT_NORMALIZED';annotation:'SYNTHETIC_AUTHORED_REFERENCE'}
export interface PosterField {key:MediaFieldKey;text:string;value:string|null;rowTop:number;bboxPx:PixelBox;bboxNorm:PixelBox;
  imageSpan:MediaImageSpan;htmlSpan:MediaTextSpan|null;evidenceId:string}
export interface PosterFixture {
  id:string;sourceId:string;authoring:'DETERMINISTIC_CODE';referenceKind:'SYNTHETIC_AUTHORED_REFERENCE';
  rights:{fixtureUse:'LOCAL_SYNTHETIC_EVALUATION';externalAi:'NOT_APPROVED';realInstitution:'NONE'};
  image:{path:string;originalSha256:string;revisionId:string;width:640;height:360;format:'PNG'};
  html:{path:string;originalSha256:string;revisionId:string;paragraphs:Array<{id:string;text:string}>};
  fields:PosterField[];expected:{eligibility:'ELIGIBLE'|'INELIGIBLE'|'UNKNOWN';applyDeadline:string|null;eventDate:string|null;
    requiredRetrievalKeys:MediaFieldKey[];rationale:string};
}
export interface TemporalFixture {
  id:string;asOf:string;scenario:string;
  revisions:Array<{revision:RevisionRecord;original:{path:string;sha256:string};paragraphs:Array<{id:string;text:string}>;
    evidence:{originalSha256:string;span:MediaTextSpan}}>;
  expected:{currentRevisionIds:string[];quarantined:Array<[string,RevisionReason]>};
}
export interface MediaFixtureManifest {
  schemaVersion:'synthetic-media-evaluation-v1';datasetId:'syn-media-time-v1';demoAsOf:string;
  referenceKind:'SYNTHETIC_AUTHORED_REFERENCE';independentHumanReview:'NOT_RUN';manifestSha256:string;
  profile:{id:'SYN-MEDIA-PROFILE';enrollment:'ENROLLED';campus:'SEOUL';cohort:2023};
  posters:PosterFixture[];temporalCases:TemporalFixture[];
}
export interface MediaAsset {path:string;bytes:Uint8Array}
