const textBytes=(s:string)=>new TextEncoder().encode(s);
function posters(assets:MediaAsset[]):PosterFixture[]{return SPECS.map(([enrollment,campus,cohort,eligibility],index)=>{
  const n=index+1,serial=String(n).padStart(3,'0'),id='SYN-MEDIA-'+serial,revisionId=id+'-IMAGE-R1',htmlRevision=id+'-HTML-R1';
  const date='2026-12-'+String(n).padStart(2,'0'),eventOnly=n%5===0,rolling=n%7===0;
  const values:Array<{key:MediaFieldKey;value:string|null;text:string}>=[
    {key:'TITLE',value:'FICTIONAL PROGRAM '+serial,text:'TITLE: FICTIONAL PROGRAM '+serial},
    eventOnly?{key:'EVENT_DATE',value:date,text:'EVENT DATE: '+date}:rolling?
      {key:'APPLY_MODE',value:'ROLLING',text:'APPLY MODE: ROLLING'}:{key:'APPLY_DEADLINE',value:date,text:'APPLY DEADLINE: '+date},
    {key:'ENROLLMENT',value:enrollment,text:'ENROLLMENT: '+(enrollment??'NOT STATED')},
    {key:'CAMPUS',value:campus,text:'CAMPUS: '+(campus??'NOT STATED')},
    {key:'COHORT_MIN',value:cohort===null?null:String(cohort),text:'COHORT MIN: '+(cohort??'NOT STATED')},
    n%2===0?{key:'PRIORITY',value:'HIGH GPA',text:'PRIORITY ONLY: HIGH GPA'}:
      {key:'COMPLETION',value:'ATTENDANCE 80',text:'COMPLETION ONLY: ATTENDANCE 80'},
  ];
  const raster=renderPosterRaster(values.map(v=>v.text)),imageSha=hashBytes(raster.bytes),imagePath='media/poster-'+serial+'.png';
  // Deliberately incomplete HTML: the original poster carries additional conditions.
  const visible=new Set(n%4===0?[0,1,2,3,4]:n%4===1?[0,1,2]:n%4===2?[0,1,3]:[0,2,4]);
  const paragraphs=values.flatMap((v,i)=>visible.has(i)?[{id:'p'+(i+1),text:v.text}]:[]);
  const html='<!doctype html>\n<html lang="en"><meta charset="utf-8"><title>'+id+'</title><body>\n'+
    '<h1>SYNTHETIC EVALUATION NOTICE</h1>\n'+paragraphs.map(p=>'<p id="'+p.id+'">'+p.text+'</p>').join('\n')+
    '\n<p>Additional conditions are in the authored poster.</p>\n</body></html>\n';
  const htmlBytes=textBytes(html),htmlSha=hashBytes(htmlBytes),htmlPath='media/poster-'+serial+'.html';
  assets.push({path:imagePath,bytes:raster.bytes},{path:htmlPath,bytes:htmlBytes});
  const fields:PosterField[]=values.map((v,i)=>{const rendered=raster.fields[i]!,b=rendered.bboxPx;
    const bboxNorm:PixelBox=[b[0]/640,b[1]/360,b[2]/640,b[3]/360],p=paragraphs.find(p=>p.id==='p'+(i+1));
    return {...v,rowTop:rendered.rowTop,bboxPx:b,bboxNorm,evidenceId:id+':'+v.key,
      imageSpan:{kind:'IMAGE',sourceRevisionId:revisionId,originalSha256:imageSha,pageIndex:0,bboxNorm:[...bboxNorm],
        quote:v.text,coordinateSystem:'ORIGINAL_TOP_LEFT_NORMALIZED',annotation:'SYNTHETIC_AUTHORED_REFERENCE'},
      htmlSpan:p?{kind:'TEXT',sourceRevisionId:htmlRevision,paragraphId:p.id,start:0,end:p.text.length,quote:p.text}:null};
  });
  return {id,sourceId:id,authoring:'DETERMINISTIC_CODE',referenceKind:'SYNTHETIC_AUTHORED_REFERENCE',
    rights:{fixtureUse:'LOCAL_SYNTHETIC_EVALUATION',externalAi:'NOT_APPROVED',realInstitution:'NONE'},
    image:{path:imagePath,originalSha256:imageSha,revisionId,width:640,height:360,format:'PNG'},
    html:{path:htmlPath,originalSha256:htmlSha,revisionId:htmlRevision,paragraphs},fields,
    expected:{eligibility,applyDeadline:eventOnly||rolling?null:date,eventDate:eventOnly?date:null,
      requiredRetrievalKeys:['ENROLLMENT','CAMPUS','COHORT_MIN'],
      rationale:eligibility==='ELIGIBLE'?'All three stated requirements match the fixed fictional profile.':
        eligibility==='INELIGIBLE'?'At least one stated requirement contradicts the fixed fictional profile.':
          'A required field is unstated; priority and completion cannot supply eligibility.'}};
});}
const time=(hours:number)=>new Date(Date.parse(DEMO_AS_OF)+hours*3600000).toISOString();
function temporalCases(assets:MediaAsset[]):TemporalFixture[]{
  const definitions:Array<{scenario:string;asOf:number;changes:Array<Partial<RevisionRecord>>;
    expectedCurrent:number[];expectedQuarantine:Array<[number,RevisionReason]>}>=[
    {scenario:'Before first fetch',asOf:-25.5,changes:[{}],expectedCurrent:[],expectedQuarantine:[[1,'NOT_KNOWN_AT_ASOF']]},
    {scenario:'Fetched but independent verification still in the future',asOf:-23.5,changes:[{}],expectedCurrent:[],expectedQuarantine:[[1,'UNVERIFIED']]},
    {scenario:'Verified first revision',asOf:-22,changes:[{}],expectedCurrent:[1],expectedQuarantine:[]},
    {scenario:'Unreviewed correction suppresses superseded claims',asOf:0,changes:[{},{status:'NEEDS_REVIEW'}],expectedCurrent:[],expectedQuarantine:[[1,'SUPERSEDED'],[2,'NOT_ACTIVE']]},
    {scenario:'Verified correction replaces old deadline',asOf:0,changes:[{},{}],expectedCurrent:[2],expectedQuarantine:[[1,'SUPERSEDED']]},
    {scenario:'Historical query cannot see later correction',asOf:-3,changes:[{},{}],expectedCurrent:[1],expectedQuarantine:[[2,'NOT_KNOWN_AT_ASOF']]},
    {scenario:'Publication is in the future',asOf:0,changes:[{publishedAt:time(1)}],expectedCurrent:[],expectedQuarantine:[[1,'FUTURE_PUBLICATION']]},
    {scenario:'Cancellation removes old claims',asOf:0,changes:[{},{status:'RETRACTED',changeKind:'CANCELLED'}],expectedCurrent:[],expectedQuarantine:[[1,'SUPERSEDED'],[2,'CANCELLED']]},
    {scenario:'Rights blocked',asOf:0,changes:[{status:'BLOCKED_RIGHTS'}],expectedCurrent:[],expectedQuarantine:[[1,'NOT_ACTIVE']]},
    {scenario:'Validity ends exactly at asOf',asOf:0,changes:[{validUntil:time(0)}],expectedCurrent:[],expectedQuarantine:[[1,'EXPIRED']]},
    {scenario:'Two competing corrections are quarantined',asOf:0,changes:[{},{},{}],expectedCurrent:[],expectedQuarantine:[[1,'SUPERSEDED'],[2,'FORKED_CHAIN'],[3,'FORKED_CHAIN']]},
    {scenario:'Correction verification in the future cannot authorize current claims',asOf:0,changes:[{},{lastVerifiedAt:time(1)}],expectedCurrent:[],expectedQuarantine:[[1,'SUPERSEDED'],[2,'UNVERIFIED']]},
  ];
  return definitions.map((d,index)=>{
    const id='SYN-TEMPORAL-'+String(index+1).padStart(2,'0'),rid=(n:number)=>id+'-R'+n;
    const revisions=d.changes.map((change,j)=>{
      const revision:RevisionRecord={revisionId:rid(j+1),sourceId:id,status:'ACTIVE',changeKind:j?'CORRECTED':'NEW',
        provenance:'SYNTHETIC',permissionRef:'SYNTHETIC-LOCAL-FIXTURE',publishedAt:time(j?-3:-25),
        fetchedAt:time(j?-2:-24),lastVerifiedAt:time(j?-1:-23),...(j?{supersedes:rid(1)}:{}),...change};
      const paragraphs=[{id:'deadline',text:'SYNTHETIC APPLICATION DEADLINE: '+(j?'2026-12-10':'2026-12-01')},
        {id:'revision',text:'Revision '+revision.revisionId+' / '+revision.changeKind+' / '+revision.status}];
      const bytes=textBytes('SYNTHETIC TEMPORAL ORIGINAL\n'+paragraphs.map(p=>p.id+'\t'+p.text).join('\n')+'\n');
      const path='temporal/'+revision.revisionId+'.txt',sha256=hashBytes(bytes);assets.push({path,bytes});
      const p=paragraphs[0]!;
      return {revision,original:{path,sha256},paragraphs,evidence:{originalSha256:sha256,
        span:{kind:'TEXT' as const,sourceRevisionId:revision.revisionId,paragraphId:p.id,start:0,end:p.text.length,quote:p.text}}};
    });
    return {id,asOf:time(d.asOf),scenario:d.scenario,revisions,expected:{
      currentRevisionIds:d.expectedCurrent.map(rid),quarantined:d.expectedQuarantine.map(([n,reason])=>[rid(n),reason] as [string,RevisionReason])}};
  });
}
export function buildMediaFixturePack():{manifest:MediaFixtureManifest;assets:MediaAsset[]}{
  const assets:MediaAsset[]=[],posterCases=posters(assets),temporal=temporalCases(assets);
  const body={schemaVersion:'synthetic-media-evaluation-v1' as const,datasetId:'syn-media-time-v1' as const,demoAsOf:DEMO_AS_OF,
    referenceKind:'SYNTHETIC_AUTHORED_REFERENCE' as const,independentHumanReview:'NOT_RUN' as const,
    profile:{id:'SYN-MEDIA-PROFILE' as const,enrollment:'ENROLLED' as const,campus:'SEOUL' as const,cohort:2023 as const},
    posters:posterCases,temporalCases:temporal};
  return {manifest:{...body,manifestSha256:hashCanonical(body)},assets};
}
/** The authored generator is the versioned canonical source; edits require a new
 * recipe/reference version and review, not a recomputed caller-controlled hash. */
export function validateMediaFixturePack(raw:unknown,assets?:ReadonlyMap<string,Uint8Array>):MediaFixtureManifest{
  const expected=buildMediaFixturePack();
  if(canonicalJson(raw)!==canonicalJson(expected.manifest))throw new Error('Modified synthetic media reference');
  if(assets){if(assets.size!==expected.assets.length)throw new Error('Unexpected fixture asset');
    for(const asset of expected.assets){const actual=assets.get(asset.path);
      if(!actual||hashBytes(actual)!==hashBytes(asset.bytes))throw new Error('Modified synthetic fixture bytes');}}
  return expected.manifest;
}
